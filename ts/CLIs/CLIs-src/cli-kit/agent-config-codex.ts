import { Errors, Try } from '@shared'
import { FileSystem, Path } from '@shared/os'
import { flattenDiagnosticMessageText, parseConfigFileTextToJson } from 'typescript'
import { agentHostCommandPrefixes } from './agent-config-claude-host'
import { type AgentProfiles, parseProfiles } from './agent-config-profiles'

const permissionsSource = '.rulesync/permissions.jsonc'
const delegationSkillPath = 'agents/skills/delegation/SKILL.md'
const profile = 'tao-workspace'
const reviewProfile = 'tao-review'

type CanonicalPermissions = {
  agentHostCommands?: unknown
  claudecode?: { sandbox?: { filesystem?: { allowWrite?: readonly string[] }; network?: NetworkPolicy } }
  permission?: { bash?: Record<string, string>; read?: Record<string, string> }
}

type NetworkPolicy = {
  allowLocalBinding?: boolean
  allowUnixSockets?: readonly string[]
  allowedDomains?: readonly string[]
}

/** parsePermissions reads canonical JSONC permissions for the custom Codex renderer. */
export function parsePermissions(source: string): CanonicalPermissions {
  const parsed = parseConfigFileTextToJson(permissionsSource, source)
  if (parsed.error !== undefined) {
    Errors.ThrowUserInput(
      `Invalid ${permissionsSource}: ${flattenDiagnosticMessageText(parsed.error.messageText, '\n')}`,
    )
  }
  if (typeof parsed.config !== 'object' || parsed.config === null || Array.isArray(parsed.config)) {
    Errors.ThrowUserInput(`${permissionsSource} must contain an object.`)
  }
  return parsed.config as CanonicalPermissions
}

/** codexDomains translates apex wildcards into Codex's recursive domain spelling. */
export function codexDomains(allowedDomains: readonly string[]): string[] {
  const wildcardApexes = allowedDomains.filter(domain => domain.startsWith('*.')).map(domain => domain.slice(2))
  const covered = (domain: string) => wildcardApexes.some(apex => domain === apex || domain.endsWith(`.${apex}`))
  const domains = allowedDomains.flatMap(domain =>
    domain.startsWith('*.') ? [`**.${domain.slice(2)}`] : covered(domain) ? [] : [domain]
  )
  return [...new Set(domains)].sort()
}

/** renderCodexConfig produces repository-local Codex permissions and delegation defaults. */
export function renderCodexConfig(
  permissions: CanonicalPermissions,
  profiles: AgentProfiles,
  delegationSkill = '',
): string {
  const read = permissions.permission?.read ?? {}
  const hostCapableRead = Object.fromEntries(Object.entries(read).filter(([, action]) => action !== 'deny'))
  const allowWrite = permissions.claudecode?.sandbox?.filesystem?.allowWrite ?? []
  const network = permissions.claudecode?.sandbox?.network ?? {}
  return [
    ...header(),
    '',
    `default_permissions = ${quote(profile)}`,
    'approval_policy = "on-request"',
    'approvals_reviewer = "auto_review"',
    '',
    '# Live retrieval so agents can research language, tooling, and dependency questions',
    '# without an approval round-trip.',
    'web_search = "live"',
    '',
    '# Required for the per-profile domain rules below to be enforced.',
    '[features]',
    'network_proxy = true',
    '',
    ...agentsSection(delegationSkill),
    ...reviewConfig(read, network),
    ...workspaceConfig(hostCapableRead, allowWrite, network),
    ...Object.entries(profiles).flatMap(([name, value]) => renderOverlayProfile(name, value)),
    '',
  ].join('\n')
}

/** renderCodexRules limits host exceptions to named operations validated by the dispatcher. */
export function renderCodexRules(permissions: CanonicalPermissions): string {
  const operations = [...new Set(agentHostCommandPrefixes(permissions).map(prefix => prefix[0]!))]
  return [
    '# Generated by `./agent setup` from .rulesync/permissions.jsonc. Edit that file, not this one.',
    '# Each named ./agent unsandboxed operation runs on the host; its editable wrapper checks deeper argv.',
    '',
    ...operations.map(operation =>
      `prefix_rule(pattern=${
        JSON.stringify(['./agent', 'unsandboxed', operation])
      }, decision="allow", justification="Repository host wrapper validates subcommands and arguments.")`
    ),
    '',
  ].join('\n')
}

/** generateCodexConfig renders the two custom Codex outputs from shared canonical sources. */
export async function generateCodexConfig(options: {
  onSkip?: (message: string) => void
  root: string
  writeText?: (path: string, content: string) => Promise<void>
}): Promise<void> {
  const permissions = parsePermissions(await FileSystem.file(Path.resolve(options.root, permissionsSource)).text())
  const typedProfiles = parseProfiles(
    await FileSystem.file(Path.resolve(options.root, '.rulesync/profiles.jsonc')).text(),
  )
  const skillPath = Path.resolve(options.root, delegationSkillPath)
  const delegationSkill = FileSystem.existsSync(skillPath) ? await FileSystem.file(skillPath).text() : ''
  const outputs = [
    {
      path: Path.resolve(options.root, '.codex/config.toml'),
      content: renderCodexConfig(permissions, typedProfiles, delegationSkill),
    },
    { path: Path.resolve(options.root, '.codex/rules/tao.rules'), content: renderCodexRules(permissions) },
  ]
  for (const output of outputs) {
    if (FileSystem.existsSync(output.path) && await FileSystem.file(output.path).text() === output.content) {
      continue
    }
    await Try(() => (options.writeText ?? writeText)(output.path, output.content), {
      catch(error) {
        const code = (error as NodeJS.ErrnoException).code
        if (code !== 'EACCES' && code !== 'EPERM') {
          return Errors.Throw(error)
        }
        const message = `Codex permissions are stale but ${output.path} is not writable. `
          + 'Pause and ask the Developer to approve an unsandboxed `./agent setup`; do not commit stale generated rules.'
        options.onSkip?.(message)
        return Errors.ThrowHostEnvironment(message)
      },
    })
  }
}

function reviewConfig(read: Record<string, string>, network: NetworkPolicy): string[] {
  return [
    `[permissions.${reviewProfile}]`,
    'extends = ":read-only"',
    'description = "Tao review: inspect the worktree and reference repository without editing them."',
    '',
    ...filesystemSection(reviewProfile, read, []),
    '',
    ...workspaceRootsSection(reviewProfile, read),
    '',
    ...networkSection(reviewProfile, { ...network, allowLocalBinding: false }, []),
    '',
  ]
}

function workspaceConfig(
  read: Record<string, string>,
  allowWrite: readonly string[],
  network: NetworkPolicy,
): string[] {
  return [
    `[permissions.${profile}]`,
    'extends = ":workspace"',
    'description = "Tao worktree: write the workspace, read the reference repo, reach documentation and package hosts."',
    '',
    ...filesystemSection(profile, read, allowWrite),
    '',
    ...networkSection(profile, network, network.allowUnixSockets ?? []),
    '',
  ]
}

function agentsSection(skill: string): string[] {
  const model = tierModels(skill, 'codex').get('standard')
  if (model === undefined) {
    return []
  }
  return [
    `# Delegation defaults. The model is the standard tier of the routing table in`,
    `# ${delegationSkillPath}, which is the one place this repository spells a model name.`,
    '[agents]',
    'enabled = true',
    `default_subagent_model = ${quote(model)}`,
    'default_subagent_reasoning_effort = "medium"',
    'max_concurrent_threads_per_session = 5',
    '',
  ]
}

function renderOverlayProfile(name: string, value: AgentProfiles[string]): string[] {
  const codexName = `tao-${name}`
  const base = value.sandbox === false ? ':danger-full-access' : value.extends ? `tao-${value.extends}` : profile
  const lines = [
    `[permissions.${codexName}]`,
    `extends = ${quote(base)}`,
    `description = ${quote(value.description)}`,
  ]
  if (value.sandbox === false) {
    return [...lines, '']
  }
  if (value.allowWrite?.length) {
    lines.push('', ...directFilesystemSection(codexName, value.allowWrite))
  }
  if (value.unixSockets?.length) {
    lines.push('', ...unixSocketSection(codexName, value.unixSockets))
  }
  return [...lines, '']
}

function filesystemSection(name: string, read: Record<string, string>, allowWrite: readonly string[]): string[] {
  return [
    `[permissions.${name}.filesystem]`,
    ...(allowWrite.length === 0 ? [] : [
      '# Caches and shared state the pinned toolchain writes outside the worktree. One list serves',
      "# both harnesses: these are Claude Code's sandbox write paths, spelled as Codex rules.",
      ...allowWrite.map(path => `${quote(path)} = "write"`),
    ]),
    '# The previous repository is reference material only (see AGENTS.md).',
    ...homePathRules(read, 'allow').map(path => `${quote(path)} = "read"`),
    ...homePathRules(read, 'deny').map(path => `${quote(path)} = "deny"`),
  ]
}

function workspaceRootsSection(name: string, read: Record<string, string>): string[] {
  const denied = workspaceRules(read, 'deny')
  return denied.length === 0 ? [] : [
    `[permissions.${name}.filesystem.":workspace_roots"]`,
    '# Keep the patterns narrow so they do not match unrelated repository files.',
    ...denied.map(pattern => `${quote(pattern)} = "deny"`),
  ]
}

function networkSection(name: string, network: NetworkPolicy, sockets: readonly string[]): string[] {
  return [
    `[permissions.${name}.network]`,
    'enabled = true',
    ...(network.allowLocalBinding
      ? [
        "# Tao's dev loop binds Metro, Studio, and the local InstantDB stack to loopback ports.",
        'allow_local_binding = true',
      ]
      : []),
    '',
    ...unixSocketSection(name, sockets),
    '',
    "# Allowlist-first: shell egress is limited to the hosts Tao's toolchain and research need.",
    `[permissions.${name}.network.domains]`,
    ...codexDomains(network.allowedDomains ?? []).map(domain => `${quote(domain)} = "allow"`),
  ]
}

function unixSocketSection(name: string, sockets: readonly string[]): string[] {
  const portable = [...new Set(sockets.filter(path => !path.startsWith('~')))]
  return portable.length === 0 ? [] : [
    `[permissions.${name}.network.unix_sockets]`,
    ...portable.map(socket => `${quote(socket)} = "allow"`),
  ]
}

function directFilesystemSection(name: string, paths: readonly string[]): string[] {
  return [`[permissions.${name}.filesystem]`, ...paths.map(path => `${quote(path)} = "write"`)]
}

function homePathRules(read: Record<string, string>, action: string): string[] {
  return Object.entries(read)
    .filter(([pattern, value]) => pattern.startsWith('~') && value === action)
    .map(([pattern]) => action === 'allow' ? pattern.replace(/\/\*\*$/, '') : pattern)
}

function workspaceRules(read: Record<string, string>, action: string): string[] {
  return Object.entries(read).filter(([pattern, value]) => !pattern.startsWith('~') && value === action).map(([path]) =>
    path
  )
}

function tierModels(skill: string, column: 'codex'): Map<string, string> {
  const models = new Map<string, string>()
  for (const line of skill.split('\n')) {
    const cells = line.split('|').map(cell => cell.trim())
    const model = cells[3]?.match(/^`([^`]+)`$/)?.[1]
    if (cells.length >= 5 && model !== undefined && /^[a-z]+$/.test(cells[1] ?? '')) {
      models.set(cells[1]!, model)
    }
  }
  return models
}

function header(): string[] {
  return [
    '# Repo-local filesystem, network, and approval settings for Tao development.',
    '# Setup adds exact Git common/worktree directory grants to the machine-local Codex user',
    '# profile. Start a fresh session after first setup or moving a checkout; session hooks',
    '# cannot extend the permissions of an already running session.',
    '# See packages/cli/agent-cli/agent-cli-src/agent-config/CodexGitPermissions.ts.',
    '#',
    '# Tracked so a new worktree has its permission profile before setup or session hooks run.',
    '# It names no login: Codex accepts only absolute Unix socket paths, so a home-relative socket',
    '# in the canonical rules is left out here and reached through a named host operation instead.',
    '#',
    `# Generated with .codex/rules/tao.rules by \`./agent setup\` from ${permissionsSource}`,
    '# and .rulesync/profiles.jsonc. Edit those canonical files, not either generated Codex output:',
    "# rulesync's own Codex translator cannot express loopback binding, Unix sockets, or a",
    '# curated domain allowlist, so this profile is rendered by',
    '# packages/cli/agent-cli/agent-cli-src/agent-config/CodexConfigGenerator.ts instead.',
    '#',
    '# The sibling .codex/hooks.json is generated from .rulesync/hooks.jsonc by the same setup and',
    '# runs `./agent setup` when a session starts, the one setup entry Worktrunk (.config/wt.toml),',
    '# Claude Code (.claude/settings.json hooks), and Cursor (.cursor/worktrees.json) reach too.',
    '# Codex trusts a repository hook once per content hash through its /hooks command.',
  ]
}

function quote(value: string): string {
  return JSON.stringify(value)
}

async function writeText(path: string, content: string): Promise<void> {
  await FileSystem.write(path, content)
}
